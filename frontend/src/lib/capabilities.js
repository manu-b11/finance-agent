/*
  Texto local de "¿Qué puedes hacer?". Se muestra sin llamar al modelo,
  para no gastar créditos en una respuesta que no depende de datos del usuario.
*/
export function capabilitiesText() {
  return `¡Hola! Soy Finly, tu asistente de finanzas personales.

Esto es lo que puedo hacer por ti:

- Registrar tus movimientos. Por ejemplo: «Gasté 25.000 en el mercado» o «Me pagaron el sueldo: 2.500.000».
- Mostrarte cómo vas. Pregúntame «¿Cómo voy este mes?» o «¿En qué gasto más?» y te explico tu balance y tus categorías.
- Llevar tu presupuesto mensual. Dime cuánto quieres gastar al mes y te cuento cuánto has usado y cuánto te queda.
- Seguir tus metas de ahorro. Crea una meta, registra tus aportes y consulta tu progreso cuando quieras.
- Leer tus facturas. Súbeme una foto o un PDF; yo extraigo los datos y tú los revisas antes de guardarlos.
- Generar informes. Te preparo tu informe mensual en PDF.
- Programar recordatorios. Por ejemplo: «Recuérdame pagar el arriendo el día 5 de cada mes».

Si me falta algún dato, te lo pregunto. Mis recomendaciones son informativas y no reemplazan la asesoría de un profesional financiero.`
}
